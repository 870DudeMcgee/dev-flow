def test_run_replay_result_frozen() -> None:
    """RunReplayResult is immutable."""
    r = RunReplayResult(run_id="r", replay_succeeded=True, snapshot_matches=True)
    with pytest.raises(Exception):
        r.run_id = "modified"  # type: ignore[misc]


def test_benchmark_result_frozen() -> None:
    """ReplayBenchmarkResult is immutable."""
    r = ReplayBenchmarkResult(
        total_runs=0,
        successful_replays=0,
        failed_replays=0,
        mismatched_snapshots=0,
        benchmark_id="b1",
        benchmarked_at="2026-01-01T00:00:00Z",
    )
    with pytest.raises(Exception):
        r.total_runs = 1  # type: ignore[misc]
