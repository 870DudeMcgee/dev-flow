"""Tests for the replay benchmark suite (M7-S1)."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from devflow.loop.models import LoopStage
from devflow.loop.pipeline_run import create_pipeline_run
from devflow.loop.replay_bench import (
    ReplayBenchmarkResult,
    RunReplayResult,
    discover_canonical_runs,
    run_replay_benchmark,
)
from devflow.loop.workflow_ledger import (
    WORKFLOW_EVENTS_FILE,
    WORKFLOW_SNAPSHOT_FILE,
    WorkflowSnapshot,
    initialize_workflow_run,
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _create_run_with_snapshot(tmp_path: Path, stage: LoopStage = LoopStage.complete) -> str:
    """Create a canonical run with events and a stored snapshot.

    The snapshot is generated by replaying the events so it matches what
    ``replay_workflow_run`` will produce during the benchmark.
    """
    from devflow.loop.workflow_ledger import replay_workflow_run

    run_id = create_pipeline_run(tmp_path, {"repo": "test/repo"})
    initialize_workflow_run(tmp_path, run_id)

    # Replay to get the actual snapshot, then store it so the benchmark matches
    snapshot = replay_workflow_run(tmp_path, run_id)
    run_dir = tmp_path / ".devflow" / "pipeline-runs" / run_id
    snapshot_path = run_dir / WORKFLOW_SNAPSHOT_FILE
    snapshot_path.write_text(
        json.dumps(snapshot.model_dump(mode="json"), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return run_id


# ---------------------------------------------------------------------------
# discover_canonical_runs tests
# ---------------------------------------------------------------------------

def test_discover_canonical_runs_finds_runs(tmp_path: Path) -> None:
    """Finds runs with snapshots."""
    _create_run_with_snapshot(tmp_path)
    _create_run_with_snapshot(tmp_path)

    runs = discover_canonical_runs(tmp_path)
    assert len(runs) == 2


def test_discover_canonical_runs_ignores_non_canonical(tmp_path: Path) -> None:
    """Runs without snapshots are not canonical."""
    create_pipeline_run(tmp_path, {"repo": "test"})  # no snapshot

    runs = discover_canonical_runs(tmp_path)
    assert len(runs) == 0


def test_discover_canonical_runs_empty(tmp_path: Path) -> None:
    """No runs → empty tuple."""
    assert discover_canonical_runs(tmp_path) == ()


# ---------------------------------------------------------------------------
# run_replay_benchmark tests
# ---------------------------------------------------------------------------

def test_frozen_corpus_replays(tmp_path: Path) -> None:
    """A canonical run with events + snapshot replays and matches."""
    run_id = _create_run_with_snapshot(tmp_path)
    result = run_replay_benchmark(tmp_path)

    assert result.total_runs == 1
    assert result.successful_replays >= 1
    assert result.failed_replays == 0
    # The snapshot should match because replay uses the same events
    first = result.results[0]
    assert first.run_id == run_id
    assert first.replay_succeeded is True


def test_replay_benchmark_empty(tmp_path: Path) -> None:
    """No runs → zero results."""
    result = run_replay_benchmark(tmp_path)

    assert result.total_runs == 0
    assert result.successful_replays == 0
    assert result.failed_replays == 0
    assert result.results == ()


def test_replay_benchmark_succeeds(tmp_path: Path) -> None:
    """Successful replays counted."""
    _create_run_with_snapshot(tmp_path)
    _create_run_with_snapshot(tmp_path)

    result = run_replay_benchmark(tmp_path)

    assert result.successful_replays == 2
    assert result.failed_replays == 0


def test_replay_snapshot_matches(tmp_path: Path) -> None:
    """snapshot_matches True for valid runs."""
    _create_run_with_snapshot(tmp_path)

    result = run_replay_benchmark(tmp_path)

    # At least one result with snapshot_matches=True
    assert any(r.snapshot_matches for r in result.results)


def test_run_replay_result_records_duration(tmp_path: Path) -> None:
    """Duration recorded."""
    _create_run_with_snapshot(tmp_path)

    result = run_replay_benchmark(tmp_path)

    assert all(r.duration_seconds >= 0.0 for r in result.results)


# ---------------------------------------------------------------------------
# Read-only test
# ---------------------------------------------------------------------------

def test_replay_benchmark_read_only(tmp_path: Path) -> None:
    """Run dir unchanged after benchmark."""
    run_id = _create_run_with_snapshot(tmp_path)
    run_dir = tmp_path / ".devflow" / "pipeline-runs" / run_id

    # Snapshot all file contents
    snapshot: dict[str, bytes] = {}
    for p in run_dir.rglob("*"):
        if p.is_file():
            snapshot[str(p.relative_to(run_dir))] = p.read_bytes()

    run_replay_benchmark(tmp_path)

    for p in run_dir.rglob("*"):
        if p.is_file():
            key = str(p.relative_to(run_dir))
            if key in snapshot:
                assert p.read_bytes() == snapshot[key]


